-- APEX Visual Designer - registered target applications
-- Installed by database/install.sql into the schema that runs it.
-- The designers only edit applications registered here as active for the current workspace.

DECLARE
  l_n NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_n FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'VD_SEQ_TARGET';
  IF l_n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE VD_SEQ_TARGET START WITH 1 INCREMENT BY 1 CACHE 20 NOCYCLE';
  END IF;
  SELECT COUNT(*) INTO l_n FROM USER_TABLES WHERE TABLE_NAME = 'VD_TARGET_APPLICATIONS';
  IF l_n = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE VD_TARGET_APPLICATIONS (
        TARGET_ID       NUMBER(10)     NOT NULL,
        WORKSPACE_ID    NUMBER(20)     NOT NULL,
        APP_ID          NUMBER(10)     NOT NULL,
        APP_ALIAS       VARCHAR2(255),
        PARSING_SCHEMA  VARCHAR2(128)  NOT NULL,
        TARGET_NAME     VARCHAR2(255)  NOT NULL,
        IS_ACTIVE       CHAR(1)        DEFAULT 'Y' NOT NULL,
        REGISTERED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        REGISTERED_BY   VARCHAR2(128),
        CONSTRAINT CK_VD_TARGET_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N')),
        CONSTRAINT PK_VD_TARGET PRIMARY KEY (TARGET_ID),
        CONSTRAINT UK_VD_TARGET_APP UNIQUE (WORKSPACE_ID, APP_ID)
      )]';
  END IF;
END;
/

CREATE OR REPLACE TRIGGER VD_TRG_TARGET_BI
BEFORE INSERT ON VD_TARGET_APPLICATIONS
FOR EACH ROW
BEGIN
  IF :NEW.TARGET_ID IS NULL THEN
    :NEW.TARGET_ID := VD_SEQ_TARGET.NEXTVAL;
  END IF;
  IF :NEW.REGISTERED_BY IS NULL THEN
    :NEW.REGISTERED_BY := COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), SYS_CONTEXT('USERENV', 'SESSION_USER'));
  END IF;
END;
/
