-- APEX Visual Designer - page backups (the export of a page before each designer write)
-- Installed by database/install.sql into the schema that runs it.

DECLARE
  l_n NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_n FROM USER_TABLES WHERE TABLE_NAME = 'VD_PAGE_BACKUPS';
  IF l_n = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE VD_PAGE_BACKUPS (
        BACKUP_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        WORKSPACE_ID  NUMBER         NOT NULL,
        APP_ID        NUMBER         NOT NULL,
        PAGE_ID       NUMBER         NOT NULL,
        SOURCE        CLOB           NOT NULL,
        SAVED_BY      VARCHAR2(128)  NOT NULL,
        SAVED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
      )]';
    EXECUTE IMMEDIATE 'CREATE INDEX VD_PB_PAGE_IX ON VD_PAGE_BACKUPS (WORKSPACE_ID, APP_ID, PAGE_ID, BACKUP_ID)';
    DBMS_OUTPUT.PUT_LINE('created VD_PAGE_BACKUPS');
  END IF;
END;

/
