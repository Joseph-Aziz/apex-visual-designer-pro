-- APEX Visual Designer - layout versions (layout board undo: the old values of each applied change)
-- Installed by database/install.sql into the schema that runs it.

DECLARE
  l_n NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_n FROM USER_TABLES WHERE TABLE_NAME = 'VD_LAYOUT_VERSIONS';
  IF l_n = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE VD_LAYOUT_VERSIONS (
        VERSION_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        WORKSPACE_ID  NUMBER         NOT NULL,
        APP_ID        NUMBER         NOT NULL,
        PAGE_ID       NUMBER         NOT NULL,
        CHANGES       CLOB           NOT NULL,
        SAVED_BY      VARCHAR2(128)  NOT NULL,
        SAVED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT VD_LV_JSON_CK CHECK (CHANGES IS JSON)
      )]';
    EXECUTE IMMEDIATE 'CREATE INDEX VD_LV_PAGE_IX ON VD_LAYOUT_VERSIONS (WORKSPACE_ID, APP_ID, PAGE_ID, VERSION_ID)';
    DBMS_OUTPUT.PUT_LINE('created VD_LAYOUT_VERSIONS');
  END IF;
END;

/
