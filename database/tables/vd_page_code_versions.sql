-- APEX Visual Designer - page code versions (Flutter Designer history)
-- Installed by database/install.sql into the schema that runs it.

DECLARE
  l_count PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO l_count FROM USER_TABLES
   WHERE TABLE_NAME = 'VD_PAGE_CODE_VERSIONS';
  IF l_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE VD_PAGE_CODE_VERSIONS (
        VERSION_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        WORKSPACE_ID  NUMBER         NOT NULL,
        APP_ID        NUMBER         NOT NULL,
        PAGE_ID       NUMBER         NOT NULL,
        INLINE_CSS    CLOB,
        JS_ONLOAD     CLOB,
        DESIGN_JSON   CLOB,
        NOTE          VARCHAR2(30)   NOT NULL,
        SAVED_BY      VARCHAR2(128)  NOT NULL,
        SAVED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT VD_PCV_NOTE_CK CHECK (NOTE IN ('ORIGINAL', 'SAVED', 'RESTORED', 'EDITED OUTSIDE')),
        CONSTRAINT VD_PCV_DESIGN_JSON_CK CHECK (DESIGN_JSON IS JSON)
      )]';
    EXECUTE IMMEDIATE 'CREATE INDEX VD_PCV_PAGE_IX ON VD_PAGE_CODE_VERSIONS (WORKSPACE_ID, APP_ID, PAGE_ID, VERSION_ID)';
    DBMS_OUTPUT.PUT_LINE('created VD_PAGE_CODE_VERSIONS');
  END IF;
END;
/
