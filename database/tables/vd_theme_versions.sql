-- APEX Visual Designer - theme versions (Theme Designer history)
-- Installed by database/install.sql into the schema &&VD_SCHEMA.

DECLARE
  l_n NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_n FROM ALL_TABLES WHERE OWNER = UPPER('&&VD_SCHEMA') AND TABLE_NAME = 'VD_THEME_VERSIONS';
  IF l_n = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE &&VD_SCHEMA..VD_THEME_VERSIONS (
        VERSION_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        WORKSPACE_ID  NUMBER         NOT NULL,
        APP_ID        NUMBER         NOT NULL,
        THEME_JSON    CLOB           NOT NULL,
        CSS           CLOB,
        JS            CLOB,
        NOTE          VARCHAR2(10)   NOT NULL,
        SAVED_BY      VARCHAR2(128)  NOT NULL,
        SAVED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT VD_TV_NOTE_CK CHECK (NOTE IN ('DRAFT', 'PUSHED', 'RESTORED')),
        CONSTRAINT VD_TV_JSON_CK CHECK (THEME_JSON IS JSON)
      )]';
    EXECUTE IMMEDIATE 'CREATE INDEX &&VD_SCHEMA..VD_TV_APP_IX ON &&VD_SCHEMA..VD_THEME_VERSIONS (WORKSPACE_ID, APP_ID, VERSION_ID)';
    DBMS_OUTPUT.PUT_LINE('created VD_THEME_VERSIONS');
  END IF;
END;

/
